export const tradeRentalCorrectionEvents = sqliteTable("trade_rental_correction_events", {
  id: text("id").primaryKey(),
  inspectionId: text("inspection_id").notNull().references(() => tradeRentalCorrections.id, { onDelete: "restrict" }),
  reportId: text("report_id").notNull().default(""),
  reportLinkId: text("report_link_id").notNull().default(""),
  firebaseUid: text("firebase_uid").notNull(),
  actorType: text("actor_type").notNull().default("system"),
  actorUid: text("actor_uid").notNull().default(""),
  eventType: text("event_type").notNull(),
  requestId: text("request_id").notNull().default(""),
  summary: text("summary").notNull().default(""),
  metadata: text("metadata").notNull().default("{}"),
  sourceIpSha256: text("source_ip_sha256").notNull().default(""),
  userAgentSha256: text("user_agent_sha256").notNull().default(""),
  createdAt: text("created_at").notNull(),
}, (table) => [
  index("trade_rental_correction_events_parent_idx").on(table.inspectionId, table.createdAt),
  check("trade_rental_events_actor_check", sql`${table.actorType} IN ('assessor', 'owner', 'viewer', 'system')`),
  check("trade_rental_events_metadata_check", sql`json_valid(${table.metadata}) AND json_type(${table.metadata}) = 'object' AND length(${table.summary}) <= 2000`),
  check("trade_rental_events_hash_check", sql`(${table.sourceIpSha256} = '' OR (length(${table.sourceIpSha256}) = 64 AND ${table.sourceIpSha256} = lower(${table.sourceIpSha256}) AND ${table.sourceIpSha256} NOT GLOB '*[^0-9a-f]*')) AND (${table.userAgentSha256} = '' OR (length(${table.userAgentSha256}) = 64 AND ${table.userAgentSha256} = lower(${table.userAgentSha256}) AND ${table.userAgentSha256} NOT GLOB '*[^0-9a-f]*'))`),
  check("trade_rental_events_time_check", sql`datetime(${table.createdAt}) IS NOT NULL`),
]);
