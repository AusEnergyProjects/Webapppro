import { sql } from "drizzle-orm";
import { check, index, integer, sqliteTable, text, uniqueIndex } from "drizzle-orm/sqlite-core";
import { tradeWorkOrders, tradeCrmJobMedia, tradeRentalReports, tradeRentalInspections as sourceInspections } from "./schema";

export const tradeRentalCorrections = sqliteTable("trade_rental_corrections", {
  id: text("id").primaryKey(),
  sourceInspectionId: text("source_inspection_id").notNull().references(() => sourceInspections.id),
  sourceReportId: text("source_report_id").notNull().references(() => tradeRentalReports.id),
  sourceReportSha256: text("source_report_sha256").notNull(),
  sourceSnapshotSha256: text("source_snapshot_sha256").notNull(),
  correctionReason: text("correction_reason").notNull().default(""),
  workOrderId: text("work_order_id").notNull().references(() => tradeWorkOrders.id, { onDelete: "restrict" }),
  firebaseUid: text("firebase_uid").notNull(),
  serviceSiteId: text("service_site_id").notNull().default(""),
  inspectionNumber: text("inspection_number").notNull(),
  jurisdiction: text("jurisdiction").notNull().default("VIC"),
  status: text("status").notNull().default("draft"),
  templateKey: text("template_key").notNull(),
  templateVersion: integer("template_version").notNull(),
  rulesEffectiveFrom: text("rules_effective_from").notNull(),
  assessmentScope: text("assessment_scope").notNull().default("current_minimum_standards"),
  moduleSelectionSnapshot: text("module_selection_snapshot").notNull(),
  selectedModulesSnapshot: text("selected_modules_snapshot"),
  propertySnapshot: text("property_snapshot").notNull().default("{}"),
  assessorUid: text("assessor_uid").notNull().default(""),
  assessorMemberId: text("assessor_member_id").notNull().default(""),
  assessorSnapshot: text("assessor_snapshot").notNull().default("{}"),
  revision: integer("revision").notNull().default(1),
  creationRequestId: text("creation_request_id").notNull().default(""),
  issuedReportId: text("issued_report_id").notNull().default(""),
  submittedAt: text("submitted_at").notNull().default(""),
  issuedAt: text("issued_at").notNull().default(""),
  supersededAt: text("superseded_at").notNull().default(""),
  createdByUid: text("created_by_uid").notNull(),
  createdAt: text("created_at").notNull(),
  updatedAt: text("updated_at").notNull(),
}, (table) => [
  uniqueIndex("trade_rental_corrections_active_job_idx").on(table.firebaseUid, table.workOrderId).where(sql`${table.status} NOT IN ('issued', 'superseded', 'withdrawn')`),
  uniqueIndex("trade_rental_corrections_report_idx").on(table.issuedReportId).where(sql`${table.issuedReportId} <> ''`),
  index("trade_rental_corrections_job_idx").on(table.firebaseUid, table.workOrderId, table.createdAt),
  check("trade_rental_corrections_source_report_sha256_check", sql`length(${table.sourceReportSha256}) = 64`),
  check("trade_rental_corrections_source_snapshot_sha256_check", sql`length(${table.sourceSnapshotSha256}) = 64`),
  check("trade_rental_corrections_reason_check", sql`length(${table.correctionReason}) <= 1000`),
  check("trade_rental_inspections_identity_check", sql`trim(${table.id}) <> '' AND trim(${table.workOrderId}) <> '' AND trim(${table.firebaseUid}) <> '' AND trim(${table.inspectionNumber}) <> '' AND ${table.jurisdiction} = 'VIC'`),
  check("trade_rental_inspections_status_check", sql`${table.status} IN ('draft', 'scheduled', 'in_progress', 'submitted', 'issuing', 'issued', 'superseded', 'withdrawn')`),
  check("trade_rental_inspections_template_check", sql`${table.templateKey} = 'vic-rental-minimum-standards' AND ${table.templateVersion} > 0 AND date(${table.rulesEffectiveFrom}) = ${table.rulesEffectiveFrom}`),
  check("trade_rental_corrections_scope_check", sql`${table.assessmentScope} IN ('current_minimum_standards', 'energy_readiness_2027')`),
  check("trade_rental_inspections_modules_check", sql`json_valid(${table.moduleSelectionSnapshot}) AND json_type(${table.moduleSelectionSnapshot}) = 'array' AND json_array_length(${table.moduleSelectionSnapshot}) BETWEEN 1 AND 4 AND json_extract(${table.moduleSelectionSnapshot}, '$[0]') = 'minimum_standards' AND coalesce(json_extract(${table.moduleSelectionSnapshot}, '$[1]'), '') IN ('', 'electrical_safety_check', 'gas_safety_check', 'smoke_alarm_check') AND coalesce(json_extract(${table.moduleSelectionSnapshot}, '$[2]'), '') IN ('', 'electrical_safety_check', 'gas_safety_check', 'smoke_alarm_check') AND coalesce(json_extract(${table.moduleSelectionSnapshot}, '$[3]'), '') IN ('', 'electrical_safety_check', 'gas_safety_check', 'smoke_alarm_check')`),
  check("trade_rental_corrections_selected_modules_check", sql`${table.selectedModulesSnapshot} IS NULL OR (json_valid(${table.selectedModulesSnapshot}) AND json_type(${table.selectedModulesSnapshot}) = 'array' AND json_array_length(${table.selectedModulesSnapshot}) BETWEEN 1 AND 4 AND json_extract(${table.selectedModulesSnapshot}, '$[0]') IN ('minimum_standards', 'electrical_safety_check', 'gas_safety_check', 'smoke_alarm_check') AND coalesce(json_extract(${table.selectedModulesSnapshot}, '$[1]'), '') IN ('', 'minimum_standards', 'electrical_safety_check', 'gas_safety_check', 'smoke_alarm_check') AND coalesce(json_extract(${table.selectedModulesSnapshot}, '$[2]'), '') IN ('', 'minimum_standards', 'electrical_safety_check', 'gas_safety_check', 'smoke_alarm_check') AND coalesce(json_extract(${table.selectedModulesSnapshot}, '$[3]'), '') IN ('', 'minimum_standards', 'electrical_safety_check', 'gas_safety_check', 'smoke_alarm_check') AND (json_array_length(${table.selectedModulesSnapshot}) < 2 OR json_extract(${table.selectedModulesSnapshot}, '$[1]') <> json_extract(${table.selectedModulesSnapshot}, '$[0]')) AND (json_array_length(${table.selectedModulesSnapshot}) < 3 OR json_extract(${table.selectedModulesSnapshot}, '$[2]') NOT IN (json_extract(${table.selectedModulesSnapshot}, '$[0]'), json_extract(${table.selectedModulesSnapshot}, '$[1]'))) AND (json_array_length(${table.selectedModulesSnapshot}) < 4 OR json_extract(${table.selectedModulesSnapshot}, '$[3]') NOT IN (json_extract(${table.selectedModulesSnapshot}, '$[0]'), json_extract(${table.selectedModulesSnapshot}, '$[1]'), json_extract(${table.selectedModulesSnapshot}, '$[2]'))))`),
  check("trade_rental_inspections_snapshots_check", sql`json_valid(${table.propertySnapshot}) AND json_type(${table.propertySnapshot}) = 'object' AND json_valid(${table.assessorSnapshot}) AND json_type(${table.assessorSnapshot}) = 'object'`),
  check("trade_rental_inspections_revision_check", sql`${table.revision} > 0`),
  check("trade_rental_inspections_lifecycle_check", sql`(${table.status} = 'issued' AND datetime(${table.issuedAt}) IS NOT NULL AND trim(${table.issuedReportId}) <> '') OR (${table.status} <> 'issued')`),
  check("trade_rental_inspections_time_check", sql`datetime(${table.createdAt}) IS NOT NULL AND datetime(${table.updatedAt}) IS NOT NULL`),
]);

export const tradeRentalCorrectionModules = sqliteTable("trade_rental_correction_modules", {
  id: text("id").primaryKey(),
  inspectionId: text("inspection_id").notNull().references(() => tradeRentalCorrections.id, { onDelete: "restrict" }),
  firebaseUid: text("firebase_uid").notNull(),
  moduleKey: text("module_key").notNull(),
  required: integer("required", { mode: "boolean" }).notNull().default(false),
  selectedRequired: integer("selected_required", { mode: "boolean" }),
  status: text("status").notNull().default("not_started"),
  templateVersion: integer("template_version").notNull(),
  templateName: text("template_name").notNull(),
  requiredCapability: text("required_capability").notNull(),
  templateSnapshot: text("template_snapshot").notNull(),
  answers: text("answers").notNull().default("{}"),
  credentialSnapshot: text("credential_snapshot").notNull().default("{}"),
  revision: integer("revision").notNull().default(1),
  completedByUid: text("completed_by_uid").notNull().default(""),
  completedAt: text("completed_at").notNull().default(""),
  createdAt: text("created_at").notNull(),
  updatedAt: text("updated_at").notNull(),
}, (table) => [
  uniqueIndex("trade_rental_correction_modules_key_idx").on(table.inspectionId, table.moduleKey),
  check("trade_rental_modules_key_check", sql`${table.moduleKey} IN ('minimum_standards', 'electrical_safety_check', 'gas_safety_check', 'smoke_alarm_check')`),
  check("trade_rental_modules_required_check", sql`(${table.moduleKey} = 'minimum_standards' AND ${table.required} = 1) OR (${table.moduleKey} <> 'minimum_standards' AND ${table.required} = 0)`),
  check("trade_rental_correction_modules_selected_required_check", sql`${table.selectedRequired} IS NULL OR ${table.selectedRequired} = 1`),
  check("trade_rental_modules_status_check", sql`${table.status} IN ('not_started', 'draft', 'complete', 'superseded')`),
  check("trade_rental_modules_snapshot_check", sql`json_valid(${table.templateSnapshot}) AND json_type(${table.templateSnapshot}) = 'object' AND json_extract(${table.templateSnapshot}, '$.key') = ${table.moduleKey} AND json_valid(${table.answers}) AND json_type(${table.answers}) = 'object' AND json_valid(${table.credentialSnapshot}) AND json_type(${table.credentialSnapshot}) = 'object'`),
  check("trade_rental_modules_revision_check", sql`${table.templateVersion} > 0 AND ${table.revision} > 0`),
  check("trade_rental_modules_completion_check", sql`(${table.status} = 'complete' AND trim(${table.completedByUid}) <> '' AND datetime(${table.completedAt}) IS NOT NULL) OR (${table.status} <> 'complete' AND ${table.completedByUid} = '' AND ${table.completedAt} = '')`),
  check("trade_rental_modules_time_check", sql`datetime(${table.createdAt}) IS NOT NULL AND datetime(${table.updatedAt}) IS NOT NULL`),
]);

